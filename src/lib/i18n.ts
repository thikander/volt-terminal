export type StringKey = keyof (typeof strings)['en'];

/** Reads settingsStore.current.language on every call, so `{t('key')}` used
 * directly in a template re-runs whenever the language setting changes —
 * no separate reactive wrapper needed. */
export function t(key: StringKey): string {
	const lang = settingsStore.current.language;
	return strings[lang]?.[key] ?? strings.en[key] ?? key;
}
